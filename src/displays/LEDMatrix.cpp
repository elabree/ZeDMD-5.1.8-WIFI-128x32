static void stationToSlug(const char *station, char *out, size_t outLen) {
  size_t j = 0;
  for (size_t i = 0; station[i] && j + 1 < outLen; i++) {
    char c = station[i];
    if (c >= 'A' && c <= 'Z') c += 32;
    if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))
      out[j++] = c;
    else if (j > 0 && out[j - 1] != '_')
      out[j++] = '_';
  }
  while (j > 0 && out[j - 1] == '_') j--;
  out[j] = '\0';
}

void LedMatrix::RenderRadioToBuffer(uint8_t *buf, const char *station,
                                    const char *title,
                                    int16_t stationX, int16_t titleX,
                                    uint8_t stR, uint8_t stG, uint8_t stB,
                                    uint8_t r, uint8_t g, uint8_t b) {
  char stationA[128];
  char titleA[256];
  latinToAscii(station, stationA, sizeof(stationA));
  latinToAscii(title,   titleA,   sizeof(titleA));
  station = stationA;
  title   = titleA;

  // --- Canvas: all at once (station name + separator + title) ---
  textCanvas->fillScreen(0);
  textCanvas->setFont(&FreeSans9pt7b);
  textCanvas->setTextWrap(false);

  // Station name: clock color, position from caller (centered or scrolling)
  {
    uint16_t stColor = ((uint16_t)(stR & 0xF8) << 8) | ((uint16_t)(stG & 0xFC) << 3) | (stB >> 3);
    textCanvas->setTextColor(stColor);
    textCanvas->setCursor(stationX, 13);
    textCanvas->print(station);
  }

  // Separator
  uint16_t grey = ((uint16_t)(60 & 0xF8) << 8) | ((uint16_t)(60 & 0xFC) << 3) | (60 >> 3);
  textCanvas->drawFastHLine(RADIO_ICON_W, 15, TOTAL_WIDTH - RADIO_ICON_W, grey);

  // Title: scrolling, baseline y=29
  {
    uint16_t col = ((uint16_t)(r & 0xF8) << 8) | ((uint16_t)(g & 0xFC) << 3) | (b >> 3);
    textCanvas->setTextColor(col);
    textCanvas->setCursor(titleX, 29);
    textCanvas->print(title);
  }

  textCanvas->setFont(nullptr);

  // Canvas → RGB888 Buffer
  const uint16_t *pixels = textCanvas->getBuffer();
  const uint32_t n = TOTAL_WIDTH * TOTAL_HEIGHT;
  for (uint32_t i = 0; i < n; i++) {
    uint16_t c      = pixels[i];
    buf[i * 3]     = (c >> 8) & 0xF8;
    buf[i * 3 + 1] = (c >> 3) & 0xFC;
    buf[i * 3 + 2] = (c << 3) & 0xF8;
  }

  // Icon area to black
  for (uint8_t cy = 0; cy < TOTAL_HEIGHT; cy++)
    for (uint8_t cx = 0; cx < RADIO_ICON_W; cx++) {
      uint32_t pos = ((uint32_t)cy * TOTAL_WIDTH + cx) * 3;
      buf[pos] = buf[pos + 1] = buf[pos + 2] = 0;
    }

  // --- Icon 32×32: LittleFS logo or fallback note ---
  char slug[32];
  stationToSlug(station, slug, sizeof(slug));
  const uint8_t *icon = GetRadioIcon(slug);  // incl. fuzzy match in GetRadioIcon()
  if (!icon) icon = RADIO_FALLBACK_ICON;

  for (uint8_t iy = 0; iy < 32; iy++) {
    for (uint8_t ix = 0; ix < 32; ix++) {
      const uint8_t *px = icon + ((uint32_t)iy * 32 + ix) * 4;
      uint8_t a = px[3];
      if (a == 0) continue;
      uint32_t pos = ((uint32_t)iy * TOTAL_WIDTH + ix) * 3;
      buf[pos]     = (uint8_t)((uint32_t)px[0] * a / 255);
      buf[pos + 1] = (uint8_t)((uint32_t)px[1] * a / 255);
      buf[pos + 2] = (uint8_t)((uint32_t)px[2] * a / 255);
    }
  }
}

