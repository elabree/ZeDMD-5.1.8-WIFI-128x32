// Converts UTF-8 and Latin-1 umlauts to ASCII substitutions (ä→ae, ö→oe, …).
// Unknown high bytes are skipped. All other bytes are copied 1:1.
static void latinToAscii(const char *src, char *dst, size_t dstLen) {
  size_t d = 0;
  for (size_t i = 0; src[i] && d + 4 < dstLen; i++) {
    uint8_t c = (uint8_t)src[i];
    if      (c < 0x80) { dst[d++] = (char)c; }      // ASCII 1:1
    else if (c == 0xC3 && src[i + 1]) {              // UTF-8 C3xx: German umlauts
      uint8_t n = (uint8_t)src[++i];
      const char *s = n==0x84?"Ae": n==0x96?"Oe": n==0x9C?"Ue":
                      n==0xA4?"ae": n==0xB6?"oe": n==0xBC?"ue":
                      n==0x9F?"ss": nullptr;
      if (s) { while (*s && d < dstLen - 1) dst[d++] = *s++; }
      else   { dst[d++] = 0xC3; dst[d++] = (char)n; } // unknown C3 sequence: pass through unchanged
    }
    else if (c == 0xC4) { dst[d++] = 'A'; dst[d++] = 'e'; } // Latin-1 Ä
    else if (c == 0xD6) { dst[d++] = 'O'; dst[d++] = 'e'; } // Latin-1 Ö
    else if (c == 0xDC) { dst[d++] = 'U'; dst[d++] = 'e'; } // Latin-1 Ü
    else if (c == 0xE4) { dst[d++] = 'a'; dst[d++] = 'e'; } // Latin-1 ä
    else if (c == 0xF6) { dst[d++] = 'o'; dst[d++] = 'e'; } // Latin-1 ö
    else if (c == 0xFC) { dst[d++] = 'u'; dst[d++] = 'e'; } // Latin-1 ü
    else if (c == 0xDF) { dst[d++] = 's'; dst[d++] = 's'; } // Latin-1 ß
    else if (c >= 0xE0) {
      // 3- or 4-byte UTF-8 sequence (Emoji etc.): pass all bytes through unchanged
      uint8_t seqLen = (c >= 0xF0) ? 4 : 3;
      if (d + seqLen < dstLen) {
        dst[d++] = (char)c;
        for (uint8_t j = 1; j < seqLen && src[i + j]; j++) dst[d++] = src[i + j];
        i += seqLen - 1;
      }
    }
    // 0x80-0xDF: orphaned continuation bytes or unknown 2-byte leads → skip
  }
  dst[d] = '\0';
}

// Returns advance width of radio title text rendered with FreeSans9pt7b.
uint16_t LedMatrix::GetRadioTitleWidth(const char *text) {
  char buf[256];
  latinToAscii(text, buf, sizeof(buf));
  textCanvas->setFont(&FreeSans9pt7b);
  int16_t x1, y1; uint16_t w, h;
  textCanvas->getTextBounds(buf, 0, 0, &x1, &y1, &w, &h);
  textCanvas->setFont(nullptr);
  return w;
}

// Returns pixel width of text rendered with FreeSansBold12pt7b + inline emojis.
uint16_t LedMatrix::GetTextGFXWidth(const char *text) {
  // Build a plain-text copy with emojis replaced by spaces for font measurement,
  // then add 11px per emoji (10px bitmap + 1px gap).
  char converted[256];
  latinToAscii(text, converted, sizeof(converted));
  char plain[256];
  uint8_t emojiCount = 0;
  const char *src = converted;
  char *dst = plain;
  while (*src && dst < plain + sizeof(plain) - 1) {
    int8_t idx = matchEmoji(&src);
    if (idx >= 0) {
      emojiCount++;
    } else {
      *dst++ = *src++;
    }
  }
  *dst = '\0';

  uint16_t textW = 0;
  if (*plain) {
    textCanvas->setFont(&FreeSansBold12pt7b);
    textCanvas->setCursor(0, 24);
    textCanvas->print(plain);
    textW = (uint16_t)textCanvas->getCursorX();
    textCanvas->setFont(nullptr);
  }
  return textW + (uint16_t)emojiCount * EMOJI_GAP;
}

// Renders text + inline emojis at position x into an RGB888 renderBuffer.
// Text is rendered in segments between emojis so each part lands at the correct
// x position — no overlap between text and emoji bitmaps.
void LedMatrix::RenderTextGFXToBuffer(uint8_t *buf, const char *text, int16_t x,
                                       uint8_t r, uint8_t g, uint8_t b) {
  char converted[256];
  latinToAscii(text, converted, sizeof(converted));

  textCanvas->fillScreen(0);
  uint16_t color565 = ((uint16_t)(r & 0xF8) << 8) | ((uint16_t)(g & 0xFC) << 3) | (b >> 3);
  textCanvas->setFont(&FreeSansBold12pt7b);
  textCanvas->setTextColor(color565);
  textCanvas->setTextWrap(false);

  struct EmojiPlacement { int16_t x; uint8_t idx; };
  EmojiPlacement placements[16];
  uint8_t numPlacements = 0;

  const char *src = converted;
  int16_t curX = x;
  char seg[128];
  char *dst = seg;

  while (*src) {
    int8_t idx = matchEmoji(&src);
    if (idx >= 0) {
      // Render accumulated text segment at curX, then advance curX by its width
      if (dst > seg) {
        *dst = '\0';
        textCanvas->setCursor(curX, 24);
        textCanvas->print(seg);
        curX = textCanvas->getCursorX();
        dst = seg;
      }
      if (numPlacements < 16)
        placements[numPlacements++] = { curX, (uint8_t)idx };
      curX += EMOJI_GAP;
    } else if (dst < seg + sizeof(seg) - 1) {
      *dst++ = *src++;
    } else {
      src++;  // buffer full — skip character
    }
  }
  // Flush remaining text segment
  if (dst > seg) {
    *dst = '\0';
    textCanvas->setCursor(curX, 24);
    textCanvas->print(seg);
  }
  textCanvas->setFont(nullptr);

  // Copy canvas → RGB888 buffer
  const uint16_t *pixels = textCanvas->getBuffer();
  const uint32_t n = TOTAL_WIDTH * TOTAL_HEIGHT;
  for (uint32_t i = 0; i < n; i++) {
    uint16_t c      = pixels[i];
    buf[i * 3]     = (c >> 8) & 0xF8;
    buf[i * 3 + 1] = (c >> 3) & 0xFC;
    buf[i * 3 + 2] = (c << 3) & 0xF8;
  }

  // Composite RGBA icons into buf — shadow (+1/+1 darkened), then icon on top
  for (uint8_t i = 0; i < numPlacements; i++) {
    const uint8_t *rgba = GetIcon(EMOJI_TABLE[placements[i].idx].iconName);
    if (!rgba) continue;  // icon not loaded — skip
    drawIconRGBAToBuffer(buf, rgba, placements[i].x + 1, EMOJI_Y0 + 1, true);
    drawIconRGBAToBuffer(buf, rgba, placements[i].x,     EMOJI_Y0,      false);
  }
}

